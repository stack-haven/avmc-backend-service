package entc

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"entgo.io/ent/entc/gen"
)

// tenantField 是租户维度字段名。它与各服务 mixins.TenantID 中的字段声明必须一致。
const tenantField = "tenant_id"

// tenantFilterFile 是派发文件的文件名（位于生成目录内）。
const tenantFilterFile = "tenant_filter.go"

// scopedNode 描述一个需要租户隔离的实体。
type scopedNode struct {
	Name string
}

// scopedNodes 从生成图推导租户隔离实体集合。
//
// 判定规则：同时具备 tenant_id 字段**且**声明了隐私策略。
//   - 只有字段没有策略 ⇒ 隔离实际不生效（例如未接入隐私体系的早期实体），
//     这种不一致由 B6 的生成期断言拦截，这里先安全地排除；
//   - 有策略没有字段 ⇒ 策略无从生效，同样交给断言。
//
// 关键点：这个集合**不是手写清单**——它每次从 schema 图重新推导，
// 因此不存在"新增实体忘记登记"的漂移可能。
func scopedNodes(g *gen.Graph) []scopedNode {
	nodes := make([]scopedNode, 0, len(g.Nodes))
	for _, n := range g.Nodes {
		if !hasTenantField(n) || n.NumPolicy() == 0 {
			continue
		}
		nodes = append(nodes, scopedNode{Name: n.Name})
	}
	sort.Slice(nodes, func(i, j int) bool { return nodes[i].Name < nodes[j].Name })
	return nodes
}

// globalScopeAnnotation 是 GlobalScope 注解在图中的键名。
const globalScopeAnnotation = "GlobalScope"

// assertTenantScope 强制"租户字段与租户策略同进同退"。
//
// 两个方向的不一致都是缺陷：
//   - 有 tenant_id 却没有策略：字段形同虚设，隔离实际不生效（静默漏洞）；
//   - 有策略却没有 tenant_id：策略无从施加，运行期一律拒绝（整表不可用）。
//
// 确实需要"保留列但不隔离"的实体必须显式标注 GlobalScope，让决定留在 schema 旁边
// 而不是隐式的。因为规则在生成期执行，漏改会直接让代码生成失败，而不是等到线上。
func assertTenantScope(g *gen.Graph) error {
	for _, n := range g.Nodes {
		has := hasTenantField(n)
		hasPolicy := n.NumPolicy() > 0
		_, global := n.Annotations[globalScopeAnnotation]

		if global {
			if hasPolicy {
				return fmt.Errorf("schema %s: 标注了 GlobalScope 却声明了隐私策略，两者互斥", n.Name)
			}
			continue
		}
		if has && !hasPolicy {
			return fmt.Errorf("schema %s: 声明了 tenant_id 但没有隐私策略，租户隔离不会生效；"+
				"请嵌入租户 mixin（含 Policy），或标注 entc.GlobalScope 明确声明为全局实体", n.Name)
		}
		if !has && hasPolicy {
			return fmt.Errorf("schema %s: 声明了隐私策略却没有 tenant_id 字段，策略无法施加", n.Name)
		}
	}
	return nil
}

func hasTenantField(n *gen.Type) bool {
	for _, f := range n.Fields {
		if f.Name == tenantField {
			return true
		}
	}
	return false
}

// writeTenantFilter 生成租户隔离派发表。
//
// 之所以生成而不是让每个服务的 rule 包手写 type switch：switch 的分支必须与
// schema 集合严格一致，手写时新增实体忘记同步会得到 fail-closed 的运行时错误
// （整表不可用），属于最需要结构性保障的一类清单。
func writeTenantFilter(target string, g *gen.Graph, placeholder bool) error {
	nodes := scopedNodes(g)
	outFile := filepath.Join(target, tenantFilterFile)
	if len(nodes) == 0 && !placeholder {
		// 没有租户实体时不生成文件，避免留下无意义产物。
		if err := os.Remove(outFile); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("removing %s: %w", outFile, err)
		}
		return nil
	}

	src, err := renderTenantFilter(nodes)
	if err != nil {
		return err
	}
	if err := os.WriteFile(outFile, src, 0o600); err != nil {
		return fmt.Errorf("writing %s: %w", outFile, err)
	}
	return nil
}

func renderTenantFilter(nodes []scopedNode) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by pkg/entgo/entc, DO NOT EDIT.\n")
	b.WriteString("\n")
	b.WriteString("package gen\n")
	b.WriteString("\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"entgo.io/ent\"\n")
	// 引导期占位文件没有任何分支，此时不能引入未使用的 sql / entql。
	if len(nodes) > 0 {
		b.WriteString("\t\"entgo.io/ent/dialect/sql\"\n")
		b.WriteString("\t\"entgo.io/ent/entql\"\n")
	}
	b.WriteString("\t\"entgo.io/ent/privacy\"\n")
	b.WriteString(")\n")
	b.WriteString("\n")

	names := make([]string, 0, len(nodes))
	for _, n := range nodes {
		names = append(names, fmt.Sprintf("%q", n.Name))
	}
	b.WriteString("// TenantScopedNodes 列出声明了租户隔离的实体（由 schema 图推导）。\n")
	b.WriteString("var TenantScopedNodes = []string{" + strings.Join(names, ", ") + "}\n")
	b.WriteString("\n")

	b.WriteString("// FilterTenantQuery 为具体查询施加租户谓词。\n")
	b.WriteString("// 未登记的查询类型返回拒绝：宁可整表不可用，也不默认放行。\n")
	b.WriteString("func FilterTenantQuery(q ent.Query, tenantID uint32) error {\n")
	b.WriteString("\tswitch q := q.(type) {\n")
	for _, n := range nodes {
		fmt.Fprintf(&b, "\tcase *%sQuery:\n", n.Name)
		fmt.Fprintf(&b, "\t\tq.Filter().WhereTenantID(entql.Uint32EQ(tenantID))\n")
	}
	b.WriteString("\tdefault:\n")
	b.WriteString("\t\treturn privacy.Denyf(\"unexpected tenant query type %T\", q)\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn privacy.Skip\n")
	b.WriteString("}\n")
	b.WriteString("\n")

	b.WriteString("// FilterTenantMutation 为 update/delete 施加租户谓词，避免跨租户改写。\n")
	b.WriteString("func FilterTenantMutation(m ent.Mutation, tenantID uint32) error {\n")
	b.WriteString("\tswitch m := m.(type) {\n")
	for _, n := range nodes {
		fmt.Fprintf(&b, "\tcase *%sMutation:\n", n.Name)
		fmt.Fprintf(&b, "\t\tm.WhereP(func(s *sql.Selector) { s.Where(sql.EQ(s.C(%q), tenantID)) })\n", tenantField)
	}
	b.WriteString("\tdefault:\n")
	b.WriteString("\t\treturn privacy.Denyf(\"unexpected tenant mutation type %T\", m)\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn privacy.Skip\n")
	b.WriteString("}\n")

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated tenant filter: %w", err)
	}
	return formatted, nil
}
